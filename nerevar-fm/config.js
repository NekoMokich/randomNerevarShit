/* ==========================================================================
   CONFIG — ВСЕ НАСТРОЙКИ ФАЙЛОВОГО МЕНЕДЖЕРА «Nerevar FM»
   ==========================================================================

   Файл лежит рядом с index.html и подключается строкой
   <script src="config.js"></script>. Сам index.html править не нужно:
   изменил здесь — обновил страницу (F5), сервер отдаёт config.js без
   кэша, поэтому правка видна сразу.

   ВАЖНО: этот файл отдаётся браузеру открыто — сюда НЕ пишут ни пароли,
   ни секреты. Пароль, порты и корневую папку настраивает server.py
   (флаги) либо config.json рядом с ним (см. README).

   ПОЛЯ:
     1. serverName    — имя сервера: вкладка и подпись в строке меню
     2. serverIcon    — буква/символ в иконке окна входа
     3. theme         — 'light' | 'dark' — оформление панели
     4. skin          — 'win9x' | 'wm' — стартовый скин:
                          win9x — классические Windows 9x (бирюзовый стол,
                                  синий градиент заголовка, объёмные кнопки)
                          wm    — WindowMaker / NeXTSTEP (чёрный стол
                                  со штриховкой, чёрные заголовки)
     5. wmtheme       — 'gray' | 'steel' | 'dark' — цветовая схема скина
                         WindowMaker (View → WindowMaker colors, ?wm=… ):
                           gray  — классический NeXT-серый (по умолчанию)
                           steel — сталь с синим хромом (SteelBlue)
                           dark  — тёмная схема (Dark / Nightmare)
     6. font          — строка font-family для всего интерфейса
                        ('' — шрифт по умолчанию)
     7. fm            — оболочка File Manager: заголовок и две стартовые
                        папки, показ скрытых файлов, подтверждение удаления,
                        размер шрифта списка. Менеджер всегда занимает
                        весь экран — размер окна не настраивается
     8. viewer        — окно просмотра (текст и картинки)
     9. about         — окно Help / About
    10. ftp           — что показывать в статусбаре и Help: адрес и порт
                        FTP. host '' — подставится location.hostname.
                        Порт и пароль берутся с сервера (config.json),
                        здесь только то, что показать человеку.
    11. rememberLayout — true: запоминать положение и размер вспомогательных
                         окон в браузере (localStorage)
   ========================================================================== */

window.CONFIG = {

  serverName: 'Nerevar FM',
  serverIcon: 'F',

  theme: 'light',              // 'light' | 'dark'
  skin: 'win9x',               // 'win9x' | 'wm'
  wmtheme: 'gray',             // 'gray' | 'steel' | 'dark' (для skin:'wm')
  font: '',                    // 'Tahoma, Verdana, sans-serif' | 'DejaVu Sans' | ''

  /* --- оболочка File Manager (всегда на весь экран) -------------------- */
  fm: {
    windowTitle: 'File Manager',
    leftPath: '/',             // что открыто в левой панели
    rightPath: '/',            // что открыто в правой панели
    showHidden: true,          // показывать файлы, начинающиеся с точки
    confirmDelete: true,        // спрашивать подтверждение перед удалением
    listSize: 13               // размер шрифта списка, px (12..16)
  },

  /* --- окно просмотра (F3 / Enter на файле) ----------------------------- */
  viewer: {
    windowTitle: 'Viewer',
    icon: 'V',
    width: 620,
    height: 460
  },

  /* --- окно Help ------------------------------------------------------- */
  about: {
    windowTitle: 'Help',
    icon: '?',
    width: 520,
    height: 420
  },

  /* --- что показывать про FTP в статусбаре и в Help --------------------- */
  ftp: {
    host: '',                  // '' — location.hostname (адрес этой страницы)
    port: 2121,                // порт FTP на сервере (config.json / --ftp-port)
    user: 'nerevar',           // логин FTP (config.json / --ftp-user)
    label: 'FTP'
  },

  rememberLayout: true          // true — помнить расположение окон
};
